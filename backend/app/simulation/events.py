"""Simulated event types (spec §5). Every recorded event carries time, type,
ticket, stage, resource and scenario."""
from __future__ import annotations

from dataclasses import dataclass

ARRIVAL = "ARRIVAL"
QUEUE_ENTER = "QUEUE_ENTER"
QUEUE_EXIT = "QUEUE_EXIT"
RESOURCE_ASSIGNED = "RESOURCE_ASSIGNED"
SERVICE_START = "SERVICE_START"
SERVICE_COMPLETE = "SERVICE_COMPLETE"
RESOURCE_RELEASED = "RESOURCE_RELEASED"
CLASSIFIED = "CLASSIFIED"
SERVICE_INTERRUPTED = "SERVICE_INTERRUPTED"
TRANSFER = "TRANSFER"
REWORK = "REWORK"
PRIORITY_ESCALATED = "PRIORITY_ESCALATED"
SLA_BREACHED = "SLA_BREACHED"
RESOURCE_FAILURE = "RESOURCE_FAILURE"
RESOURCE_RECOVERY = "RESOURCE_RECOVERY"
SHIFT_START = "SHIFT_START"
SHIFT_END = "SHIFT_END"
HOLD_RELEASED = "HOLD_RELEASED"
TICKET_CLOSED = "TICKET_CLOSED"
BACKLOG_CARRYOVER = "BACKLOG_CARRYOVER"

ALL_TYPES = [
    ARRIVAL, QUEUE_ENTER, QUEUE_EXIT, RESOURCE_ASSIGNED, SERVICE_START, SERVICE_COMPLETE, RESOURCE_RELEASED,
    CLASSIFIED, SERVICE_INTERRUPTED, TRANSFER, REWORK, PRIORITY_ESCALATED, SLA_BREACHED, RESOURCE_FAILURE,
    RESOURCE_RECOVERY, SHIFT_START, SHIFT_END, HOLD_RELEASED, TICKET_CLOSED, BACKLOG_CARRYOVER,
]


@dataclass(frozen=True)
class RecordedEvent:
    minute: float
    event_type: str
    ticket_ref: str | None
    stage: str | None
    resource_id: str | None
    detail: str | None = None
